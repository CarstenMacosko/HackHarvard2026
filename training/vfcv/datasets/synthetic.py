"""Synthetic movement datasets with rule-derived MDS-UPDRS-style labels.

No openly downloadable, clinician-rated finger-tapping or tremor video dataset exists (see
training/DATASETS.md). Until the team obtains one (e.g. TULIP, by request), these datasets
let a study model be built and tested end to end:

- Each example is a hand landmark track (.npz) with known ground truth, generated by
  services/cv/app/synthetic.py and measured by the product's real module code.
- Its label applies the written MDS-UPDRS anchor definitions to that ground truth. Where the
  scale uses words ("slight slowing"), the numeric cut-offs below are our assumptions,
  chosen for illustration. They are not clinical thresholds.

A model trained here learns to reproduce these rules from noisy measurements. That checks the
pipeline and the features; it says nothing about agreement with clinicians.
"""
