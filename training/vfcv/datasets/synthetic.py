# ---------- label rules ----------


def updrs_3_4(rate_hz: float, amplitude: float, decrement: float, onset: float, hesitations: int, freeze_s: float) -> int:
    """Finger tapping 0-4 from the scale's anchors: interruptions, slowing, amplitude decrement.
    The rating is the highest domain score, as the scale instructs."""
    if amplitude < 0.25 or rate_hz < 1.0:
        return 4  # "cannot or can only barely perform the task"
    interruptions = 0 if hesitations == 0 else 1 if hesitations <= 2 else 2 if hesitations <= 5 else 3
    if freeze_s >= 1.0:
        interruptions = 3  # "at least one longer arrest (freeze)"
    # assumed cut-offs for "slight / mild / moderate slowing" (healthy maximal tapping is ~3-5 Hz)
    slowing = 0 if rate_hz >= 3.0 else 1 if rate_hz >= 2.5 else 2 if rate_hz >= 1.8 else 3
    if decrement < 0.2:
        decrement_score = 0
    else:  # decrement "near the end" / "midway" / "starting after the first tap"
        decrement_score = 1 if onset >= 0.66 else 2 if onset >= 0.33 else 3
    return max(interruptions, slowing, decrement_score)


def updrs_3_17(amplitude_cm: float) -> int:
    """Rest tremor amplitude 0-4: none, ≤1 cm, 1-3 cm, 3-10 cm, ≥10 cm (maximal amplitude)."""
    if amplitude_cm <= 0.05:
        return 0
    return 1 if amplitude_cm <= 1 else 2 if amplitude_cm < 3 else 3 if amplitude_cm < 10 else 4


# ---------- generators ----------


def load_tapping(n: int = 600, seed: int = 0) -> list[Example]:
    from app.modules.hands import save_track
    from app.synthetic import tap_distance, tapping_track

    root = cache_dir("synthetic", f"tapping_v{GENERATOR_VERSION}_s{seed}")
    rng = np.random.default_rng(seed)
    out = []
    for i in range(n):
        p = {
            "rate_hz": float(rng.uniform(0.8, 5.0)),
            "amplitude": float(rng.uniform(0.15, 1.3)),
            "decrement": 0.0 if rng.random() < 0.4 else float(rng.uniform(0.2, 0.7)),
            "decrement_onset": float(rng.uniform(0.0, 0.9)),
            "hesitations": int(rng.choice([0, 0, 0, 1, 2, 3, 4, 5, 6, 8])),
            "freeze_s": 0.0 if rng.random() < 0.85 else float(rng.uniform(1.0, 2.0)),
            "rate_slowing": float(rng.uniform(0, 0.3)),
            "irregularity": float(rng.uniform(0, 0.25)),
            "seconds": float(rng.uniform(10, 15)),
            "fps": float(rng.choice([24.0, 30.0, 60.0])),
        }
        jitter, missing = float(rng.uniform(0.002, 0.01)), float(rng.uniform(0, 0.15))
        path = root / f"tap_{i:04d}.npz"
        if not path.exists():
            d = tap_distance(seed=seed * 100000 + i, **p)
            save_track(path, tapping_track(d, fps=p["fps"], jitter=jitter, missing=missing, seed=seed * 100000 + i))
        label = updrs_3_4(p["rate_hz"], p["amplitude"], p["decrement"], p["decrement_onset"], p["hesitations"], p["freeze_s"])
        out.append(
            Example(
                id=f"synthetic_tapping:v{GENERATOR_VERSION}:{seed}:{i}",
                group=f"tap{seed}_{i}",
                media_path=str(path),
                labels={
                    "updrs_3_4": float(label),
                    "rate_hz": p["rate_hz"],
                    "decrement": p["decrement"],
                    "interruptions": float(p["hesitations"] + (p["freeze_s"] > 0)),
                },
                meta={"fps": str(int(p["fps"]))},
            )
        )
    return out


def load_tremor(n: int = 600, seed: int = 0) -> list[Example]:
    from app.modules.hands import save_track
    from app.synthetic import tremor_track

    root = cache_dir("synthetic", f"tremor_v{GENERATOR_VERSION}_s{seed}")
    rng = np.random.default_rng(seed)
    out = []
    for i in range(n):
        hand_cm = 0.0 if rng.random() < 0.25 else float(np.exp(rng.uniform(np.log(0.2), np.log(12.0))))
        finger_cm = float(rng.uniform(0, 1.0)) * max(hand_cm, float(rng.uniform(0, 1.5)))
        p = {
            "freq_hz": float(rng.uniform(3.5, 11.0)),
            "amplitude": hand_cm / HAND_SIZE_CM,
            "finger_amplitude": finger_cm / HAND_SIZE_CM,
            "seconds": float(rng.uniform(10, 15)),
            "fps": float(rng.choice([24.0, 30.0, 60.0])),
            "direction_deg": float(rng.uniform(0, 180)),
            "drift": float(rng.uniform(0, 0.15)),
            "jitter": float(rng.uniform(0.002, 0.008)),
            "missing": float(rng.uniform(0, 0.1)),
            "scale_px": float(rng.uniform(80, 260)),
        }
        path = root / f"tremor_{i:04d}.npz"
        if not path.exists():
            save_track(path, tremor_track(seed=seed * 100000 + i, **p))
        amplitude_cm = max(hand_cm, finger_cm)
        out.append(
            Example(
                id=f"synthetic_tremor:v{GENERATOR_VERSION}:{seed}:{i}",
                group=f"tremor{seed}_{i}",
                media_path=str(path),
                labels={"updrs_3_17": float(updrs_3_17(amplitude_cm)), "amplitude_cm": amplitude_cm, "freq_hz": p["freq_hz"]},
                meta={"fps": str(int(p["fps"]))},
            )
        )
    return out
