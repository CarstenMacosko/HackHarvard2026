"""Calibrate a module's quality gate against expert usability labels.

A quality gate should reject captures experts could not use and keep the ones they could. For
each one-sided check (minimum sharpness, minimum skin coverage, ...) this reports how well the
check's value separates usable from unusable captures (AUC), what the current threshold keeps
and rejects, and two alternative thresholds: the one that keeps 95% of usable captures, and the
one that maximises Youden's J (sensitivity + specificity - 1).

    python -m vfcv.calibrate eczema_photo scin --option include_ungradable=true --label gradable

Writes training/calibration/<module>_<dataset>.md and .json. Changing a module's defaults is a
separate, reviewed decision (it changes which participant captures are accepted).
"""
from __future__ import annotations

import argparse
import json

import numpy as np

from . import datasets
from .evaluate import auc
from .features import measure_all, module_info
from .paths import TRAINING

# checks where a larger value is better; exposure is two-sided and reported as a pass rate only
ONE_SIDED = {"blur", "skin_coverage", "hand_visible", "duration_s", "fps"}


def calibrate(module_id: str, dataset: str, options: dict, label: str) -> dict:
    info = module_info(module_id)
    examples = [e for e in datasets.load(dataset, options) if label in e.labels]
    measured = measure_all(module_id, examples)
    usable = np.array([e.labels[label] >= 0.5 for e in examples])
    out = {"module": f"{module_id}@{info['version']}", "dataset": dataset, "label": label, "n": len(examples), "n_usable": int(usable.sum()), "checks": {}}
    for name, threshold in info["default_criteria"].items():
        check = name.removesuffix("_min").removesuffix("_max")
        values = np.array([np.nan if measured[e.id].checks.get(check) is None else measured[e.id].checks[check] for e in examples], dtype=float)
        ok = ~np.isnan(values)
        if not ok.any() or check in out["checks"]:
            continue
        v, u = values[ok], usable[ok]
        row = {"n": int(ok.sum()), "current_threshold": threshold}
        passed = np.array([measured[e.id].checks.get(check) is not None and check not in measured[e.id].failed for e in examples])[ok]
        row["current_keeps_usable"] = float(passed[u].mean()) if u.any() else None
        row["current_rejects_unusable"] = float((~passed[~u]).mean()) if (~u).any() else None
        if check in ONE_SIDED:
            row["auc"] = auc(v, u)
            row["usable_percentiles"] = {str(q): float(np.percentile(v[u], q)) for q in (5, 10, 25, 50)}
            keep95 = float(np.percentile(v[u], 5))
            row["keep95_threshold"] = keep95
            row["keep95_rejects_unusable"] = float((v[~u] < keep95).mean()) if (~u).any() else None
            cands = np.unique(np.percentile(v, np.linspace(1, 99, 99)))
            j = [((v[u] >= t).mean() + (v[~u] < t).mean() - 1, t) for t in cands]
            best_j, best_t = max(j)
            row["youden_threshold"] = float(best_t)
            row["youden_j"] = float(best_j)
            row["youden_keeps_usable"] = float((v[u] >= best_t).mean())
            row["youden_rejects_unusable"] = float((v[~u] < best_t).mean())
        out["checks"][check] = row
    return out


def _p(x) -> str:
    return "–" if x is None else f"{x * 100:.0f}%"


def markdown(r: dict, title: str) -> str:
    lines = [
        f"# Quality-gate calibration: {r['module']} on {title}",
        "",
        f"{r['n']} captures, {r['n_usable']} labelled usable (`{r['label']}`). Generated by `python -m vfcv.calibrate`.",
        "",
        "| Check | AUC | Current threshold: keeps usable / rejects unusable | Keep-95% threshold (rejects unusable) | Youden threshold: keeps / rejects |",
        "|---|---|---|---|---|",
    ]
    for name, c in r["checks"].items():
        auc_s = f"{c['auc']:.3f}" if c.get("auc") is not None else "–"
        cur = f"{c['current_threshold']}: {_p(c['current_keeps_usable'])} / {_p(c['current_rejects_unusable'])}"
        k95 = f"{c['keep95_threshold']:.3g} ({_p(c['keep95_rejects_unusable'])})" if "keep95_threshold" in c else "–"
        yj = f"{c['youden_threshold']:.3g}: {_p(c['youden_keeps_usable'])} / {_p(c['youden_rejects_unusable'])}" if "youden_threshold" in c else "–"
        lines.append(f"| {name} | {auc_s} | {cur} | {k95} | {yj} |")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(prog="python -m vfcv.calibrate")
    ap.add_argument("module")
    ap.add_argument("dataset")
    ap.add_argument("--label", required=True, help="binary label: 1 = usable capture")
    ap.add_argument("--option", action="append", default=[], help="dataset option key=value (true/false/numbers parsed)")
    args = ap.parse_args(argv)
    options = {}
    for kv in args.option:
        k, v = kv.split("=", 1)
        options[k] = {"true": True, "false": False}.get(v.lower(), int(v) if v.isdigit() else v)
    r = calibrate(args.module, args.dataset, options, args.label)
    out = TRAINING / "calibration"
    out.mkdir(exist_ok=True)
    stem = f"{args.module}_{args.dataset}"
    (out / f"{stem}.json").write_text(json.dumps(r, indent=1) + "\n")
    md = markdown(r, datasets.info(args.dataset, options).title)
    (out / f"{stem}.md").write_text(md)
    print(md)


if __name__ == "__main__":
    main()
