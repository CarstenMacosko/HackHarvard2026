// Writes supabase/seed.sql. Demo state is empty — product data is created via the app.
//   npx tsx apps/web/scripts/make-seed.ts
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { generate } from "../lib/demo-data";

export function buildSeeds(): { seed: string } {
  const s = generate();
  const seed =
    "-- No sample studies or participants. Create studies in the researcher portal.\n" +
    `-- generate() currently has ${s.studies.length} studies / ${s.participants.length} participants.\n` +
    "-- Generated by apps/web/scripts/make-seed.ts. Do not edit by hand.\n";
  return { seed };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
  writeFileSync(join(root, "supabase/seed.sql"), buildSeeds().seed);
  console.log("wrote supabase/seed.sql");
}
