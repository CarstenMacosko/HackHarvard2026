// Writes supabase/seed.sql (studies, protocols, empty participant accounts, open check-ins) from
// the same starting state the app uses without a database (lib/demo-data.ts).
// Times are written relative to now(), so the history always ends today.
//   npx tsx apps/web/scripts/make-seed.ts
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { generate } from "../lib/demo-data";

/** A fixed clock for the generator; every timestamp is written as an offset from it. */
const ANCHOR = Date.UTC(2026, 0, 1);
const TIME_COLUMNS = new Set(["due_at", "completed_at", "created_at", "captured_at", "reviewed_at", "enrolled_at", "consented_at"]);

/** 3571810841 → "41 days 08:10:10.841" (a Postgres interval) */
function span(ms: number): string {
  const days = Math.floor(ms / 86_400_000);
  const rest = new Date(ms % 86_400_000).toISOString().slice(11, 23).replace(/\.000$/, "").replace(/^00:00:00$/, "");
  return [days ? `${days} days` : "", rest].filter(Boolean).join(" ");
}

function literal(column: string, v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (TIME_COLUMNS.has(column) && typeof v === "string") {
    const ms = Date.parse(v) - ANCHOR;
    return ms === 0 ? "now()" : `now() ${ms < 0 ? "-" : "+"} interval '${span(Math.abs(ms))}'`;
  }
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
}

function insert(table: string, rows: object[], columns: string[], conflict = "on conflict do nothing"): string {
  if (!rows.length) return "";
  const values = rows.map((r) => `  (${columns.map((c) => literal(c, (r as Record<string, unknown>)[c])).join(", ")})`).join(",\n");
  return `insert into ${table} (${columns.join(", ")}) values\n${values}\n${conflict};\n`;
}

export function buildSeeds(): { seed: string } {
  const s = generate(ANCHOR);
  const seed = [
    "-- Starting data: the three study definitions and their protocols, one empty participant account and one\n" +
      "-- open invitation per study, and each account's first check-in (due now). No history: everything else comes from real uploads.\n" +
      "-- Generated by apps/web/scripts/make-seed.ts from apps/web/lib/demo-data.ts. Do not edit by hand.\n\n",
    insert("studies", s.studies.map((x) => ({ ...x })), ["id", "name", "condition", "status"]),
    insert("protocols", s.studies.map((x) => ({ study_id: x.id, version: x.protocol.version, config: x.protocol })), ["study_id", "version", "config"]),
    insert(
      "participants",
      s.participants.map((p) => ({ ...p, consented_at: p.enrolled_at })),
      ["id", "study_id", "display_name", "phone", "invite_code", "status", "preferred_time", "consented_at", "enrolled_at"],
    ),
    insert("scheduled_tasks", s.scheduledTasks, ["id", "participant_id", "task_id", "due_at", "window_hours", "status", "completed_at"]),
  ].join("\n");
  return { seed };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
  writeFileSync(join(root, "supabase/seed.sql"), buildSeeds().seed);
  console.log("wrote supabase/seed.sql");
}
