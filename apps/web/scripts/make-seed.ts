// Writes supabase/seed.sql (studies, protocols, participants, open check-ins) and
// supabase/seed_demo.sql (six weeks of synthetic history) from the same generator the app's
// demo mode uses (lib/demo-data.ts), so a Supabase project looks exactly like demo mode.
// Times are written relative to now(), so the history always ends today.
//   npx tsx apps/web/scripts/make-seed.ts
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { isOpen } from "@vf/shared";
import { generate } from "../lib/demo-data";

/** A fixed clock for the generator; every timestamp is written as an offset from it. */
const ANCHOR = Date.UTC(2026, 0, 1);
const TIME_COLUMNS = new Set(["due_at", "completed_at", "created_at", "captured_at", "reviewed_at", "enrolled_at", "consented_at"]);

/** A stable uuid for a seeded row whose table uses uuid keys, so re-running the seed inserts nothing new. */
function uuidFrom(key: string): string {
  let hex = "";
  for (let round = 0; hex.length < 32; round++) {
    let h = 0x811c9dc5 ^ round; // FNV-1a
    for (const ch of key) h = Math.imul(h ^ ch.charCodeAt(0), 0x01000193);
    hex += (h >>> 0).toString(16).padStart(8, "0");
  }
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-4${hex.slice(13, 16)}-a${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
}

/** 3571810841 → "41 days 08:10:10.841" (a Postgres interval) */
function span(ms: number): string {
  const days = Math.floor(ms / 86_400_000);
  const rest = new Date(ms % 86_400_000).toISOString().slice(11, 23).replace(/\.000$/, "").replace(/^00:00:00$/, "");
  return [days ? `${days} days` : "", rest].filter(Boolean).join(" ");
}

function literal(column: string, v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (TIME_COLUMNS.has(column) && typeof v === "string") {
    const ms = Date.parse(v) - ANCHOR;
    return ms === 0 ? "now()" : `now() ${ms < 0 ? "-" : "+"} interval '${span(Math.abs(ms))}'`;
  }
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
}

function insert(table: string, rows: object[], columns: string[], conflict = "on conflict do nothing"): string {
  if (!rows.length) return "";
  const values = rows.map((r) => `  (${columns.map((c) => literal(c, (r as Record<string, unknown>)[c])).join(", ")})`).join(",\n");
  return `insert into ${table} (${columns.join(", ")}) values\n${values}\n${conflict};\n`;
}

export function buildSeeds(): { seed: string; demo: string } {
  const s = generate(ANCHOR);
  const open = s.scheduledTasks.filter((t) => isOpen(t));
  const past = s.scheduledTasks.filter((t) => !isOpen(t));
  const header = (what: string) =>
    `-- ${what}\n-- Generated by apps/web/scripts/make-seed.ts from apps/web/lib/demo-data.ts. Do not edit by hand.\n-- All participants and data are synthetic.\n\n`;

  const seed = [
    header("Core seed: the three demo studies, their protocols, 16 participants and each active participant's open check-in."),
    insert("studies", s.studies.map((x) => ({ ...x })), ["id", "name", "condition", "status"]),
    insert("protocols", s.studies.map((x) => ({ study_id: x.id, version: x.protocol.version, config: x.protocol })), ["study_id", "version", "config"]),
    insert(
      "participants",
      s.participants.map((p) => ({ ...p, consented_at: p.enrolled_at })),
      ["id", "study_id", "display_name", "phone", "invite_code", "status", "preferred_time", "consented_at", "enrolled_at"],
    ),
    "-- one open check-in per active participant, due now, so the first usable capture earns points\n",
    insert("scheduled_tasks", open, ["id", "participant_id", "task_id", "due_at", "window_hours", "status", "completed_at"]),
  ].join("\n");

  const audit = s.audit.map((a) => `  (${["actor", "action", "entity", "entity_id", "detail", "created_at"].map((c) => literal(c, a[c as keyof typeof a])).join(", ")})`);
  const demo = [
    header("Optional demo history: six weeks of check-ins, attempts, reviews and rewards. Run after setup.sql (safe to re-run)."),
    insert("scheduled_tasks", past, ["id", "participant_id", "task_id", "due_at", "window_hours", "status", "completed_at"]),
    insert("observations", s.observations.map((o) => ({ ...o, created_at: o.captured_at })), [
      "id", "created_at", "study_id", "participant_id", "submission_id", "module", "task_label", "captured_at", "media_url", "quality", "measurements", "features",
      "model_version", "patient_report", "context", "review_status", "reviewer", "reviewed_at", "review_note",
    ]),
    insert("submissions", s.submissions, [
      "id", "participant_id", "study_id", "task_id", "scheduled_task_id", "attempt", "source", "media_type", "media_url", "analysis_runtime", "quality",
      "accepted", "observation_id", "escalated", "created_at",
    ]),
    insert("reviews", s.reviews.map((r) => ({ ...r, id: uuidFrom(r.id) })), ["id", "observation_id", "reviewer", "decision", "corrected_measurements", "before_measurements", "note", "created_at"]),
    insert("reward_events", s.rewardEvents, ["id", "participant_id", "kind", "points", "reason", "created_at"]),
    insert("redemptions", s.redemptions, ["id", "participant_id", "tier", "points", "payout_label", "mock_code", "created_at"]),
    audit.length
      ? `insert into audit_log (actor, action, entity, entity_id, detail, created_at)\nselect * from (values\n${audit.join(",\n")}\n) v (actor, action, entity, entity_id, detail, created_at)\nwhere not exists (select 1 from audit_log a where a.action = v.action and a.entity_id = v.entity_id);\n`
      : "",
  ].join("\n");
  return { seed, demo };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
  const { seed, demo } = buildSeeds();
  writeFileSync(join(root, "supabase/seed.sql"), seed);
  writeFileSync(join(root, "supabase/seed_demo.sql"), demo);
  console.log("wrote supabase/seed.sql and supabase/seed_demo.sql");
}
